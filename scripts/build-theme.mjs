// Generates src/theme.css: the colour system for light (default) and dark themes.
//
// Components use Tailwind palette classes (bg-slate-900, text-emerald-300, ...) written for a
// dark surface. Instead of rewriting every component, each palette is re-mapped per theme:
//   - dark theme: the "true" scales below (50 = lightest ... 950 = darkest)
//   - light theme: neutral scale inverted (surfaces become white/grey, text becomes dark) and
//     hue scales shifted so text stays readable on white and tints stay soft.
// `.palette-fixed` keeps the true scales inside page previews, which are designed as light pages.
//
// Run: node scripts/build-theme.mjs
import { writeFileSync } from 'node:fs';

const STEPS = ['50', '100', '200', '300', '400', '500', '600', '700', '800', '900', '950'];

const neutral = ['#f7f8fa', '#eef0f3', '#dfe2e7', '#c4c9d1', '#9aa1ac', '#737b87', '#535a66', '#383d47', '#262a31', '#1a1d22', '#121418'];
const neutralLight = {
  50: '#0d1118', 100: '#161b24', 200: '#232a36', 300: '#363f4d', 400: '#4d5665', 500: '#687183',
  600: '#9aa3b2', 700: '#d3d9e2', 800: '#e7ebf1', 900: '#ffffff', 950: '#f2f5f9',
};

const families = {
  blue: ['#eef4ff', '#d9e6ff', '#bcd2ff', '#8eb4fd', '#5b8ff8', '#3a6ff0', '#2456d6', '#1d45ad', '#1d3c8b', '#1d356f', '#142246'],
  violet: ['#f4f2ff', '#ebe6ff', '#d9d0ff', '#bdaeff', '#9d84fb', '#835cf4', '#7140e8', '#6131cc', '#512aa6', '#442787', '#29175b'],
  teal: ['#effcfa', '#c9f5ef', '#95eadf', '#5bd7ca', '#2dbcb1', '#159f96', '#0e7f7a', '#0f6663', '#115250', '#134443', '#052828'],
  green: ['#ecfbf2', '#d2f5e0', '#a8eac4', '#70d6a1', '#3dbb7c', '#1f9e62', '#14804f', '#136642', '#145137', '#13432f', '#072619'],
  amber: ['#fff8eb', '#feecc7', '#fdd78a', '#fbbd4d', '#f9a325', '#f0850d', '#d46508', '#b0470b', '#8f3810', '#752f11', '#431605'],
  red: ['#fff1f2', '#ffe1e3', '#ffc8cd', '#ffa0a8', '#fb6b78', '#f2404f', '#dc2537', '#b91b2c', '#9a1a2a', '#821a29', '#480812'],
};

// Tailwind palette name -> family.
const aliases = {
  indigo: 'blue', blue: 'blue', sky: 'blue',
  purple: 'violet', violet: 'violet', fuchsia: 'violet',
  teal: 'teal', cyan: 'teal',
  emerald: 'green', green: 'green',
  amber: 'amber', yellow: 'amber', orange: 'amber',
  rose: 'red', red: 'red', pink: 'red',
};

// Light theme: which true step each class step uses.
const lightHueMap = { 50: 900, 100: 900, 200: 800, 300: 700, 400: 700, 500: 600, 600: 600, 700: 300, 800: 200, 900: 100, 950: 50 };

const trueVars = () => {
  const lines = [];
  STEPS.forEach((s, i) => lines.push(`--color-slate-${s}: ${neutral[i]};`));
  for (const [name, fam] of Object.entries(aliases)) {
    STEPS.forEach((s, i) => lines.push(`--color-${name}-${s}: ${families[fam][i]};`));
  }
  return lines;
};

const lightVars = () => {
  const lines = [];
  STEPS.forEach((s) => lines.push(`--color-slate-${s}: ${neutralLight[s]};`));
  for (const [name, fam] of Object.entries(aliases)) {
    STEPS.forEach((s) => lines.push(`--color-${name}-${s}: ${families[fam][STEPS.indexOf(String(lightHueMap[s]))]};`));
  }
  return lines;
};

const indent = (lines, n) => lines.map((l) => ' '.repeat(n) + l).join('\n');

const css = `/* GENERATED by scripts/build-theme.mjs — edit the script, not this file. */

@theme {
${indent(trueVars(), 2)}
}

/* Light theme (default). */
:root[data-theme="light"] {
  color-scheme: light;
${indent(lightVars(), 2)}
}

/* Page previews are designed as light web pages: keep the true scales there in every theme. */
:root[data-theme="light"] .palette-fixed {
${indent(trueVars(), 2)}
}
`;

writeFileSync(new URL('../src/theme.css', import.meta.url), css);
console.log('wrote src/theme.css');
